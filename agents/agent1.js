/****************************************************************************
 * ФУНКЦИЯ ДЛЯ ТОЧЕЧНОЙ ЗАМЕНЫ ТЕКСТА ВНУТРИ JSON-МАТРИЦЫ ПЕРЕВОДОВ
 ****************************************************************************/
function updateHubWindow(html, windowId, newData) {
    const windowKey = `window${windowId}: {`;
    const startIndex = html.indexOf(windowKey);
    if (startIndex === -1) return html;

    // Ищем закрывающую фигурную скобку этого окна
    const endIndex = html.indexOf('},', startIndex);
    if (endIndex === -1) return html;

    // Шаблон для вставки нового структурированного мультиязычного контента окна
    const updatedWindowChunk = `window${windowId}: {
                    title: "${newData.title}",
                    items: [${newData.items.map(i => `"${i}"`).join(', ')}],
                    fullTitle: "${newData.fullTitle}",
                    fullText: "${newData.fullText}"`;

    // Заменяем старый кусок кода в html файле на новый
    return html.substring(0, startIndex) + updatedWindowChunk + html.substring(endIndex);
}

